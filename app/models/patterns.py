"""报文模型公开复用的正则表达式。"""

# yyyy-MM-dd，例如 2026-08-18。
DATE_YYYY_MM_DD_PATTERN = (
    r"^[0-9]{4}-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12][0-9]|3[01])$"
)

# HH:mm:ss.SSS，例如 11:41:00.000。
TIME_HH_MM_SS_SSS_PATTERN = (
    r"^(?:[01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]\.[0-9]{3}$"
)

# yyyyMMdd，例如 20260818。
DATE_YYYYMMDD_PATTERN = (
    r"^[0-9]{4}(?:0[1-9]|1[0-2])(?:0[1-9]|[12][0-9]|3[01])$"
)
